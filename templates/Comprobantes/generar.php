/** Si ObjetoImp=02 y faltan impuestos federales, aplica IVA 16 % por defecto. */
function cfdiNormalizarImpuestosConceptos02() {
    conceptos.forEach(function (c) {
        if (String(c.ObjetoImp || '') !== '02') {
            return;
        }
        var tiene = false;
        if (c.Impuestos) {
            if (c.Impuestos.Traslados && c.Impuestos.Traslados.length) {
                tiene = true;
            }
            if (c.Impuestos.Retenidos && c.Impuestos.Retenidos.length) {
                tiene = true;
            }
        }
        if (tiene) {
            return;
        }
        var baseExact = cfdiGetBaseExactConcepto(c);
        if (isNaN(baseExact) || baseExact < 0) {
            baseExact = 0;
        }
        cfdiWithFactorRedondeo(c, function () {
