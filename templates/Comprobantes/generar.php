    function fetchSuggestions(q) {
      var url = _ubAcUrl + '?tipo=' + encodeURIComponent(tipo === 'OR' ? 'Origen' : 'Destino') + '&q=' + encodeURIComponent(q);
      fetch(url)
        .then(function(r) { return r.json(); })
        .then(function(data) { renderList(data); })
        .catch(function(e) { console.warn('[ub-ac] fetch error', e); list.style.display = 'none'; });
    }

    function renderList(items) {
      list.innerHTML = '';
      if (!items || items.length === 0) {
        var empty = document.createElement('div');
        empty.className = 'ub-ac-empty';
        empty.textContent = 'Sin resultados';
        list.appendChild(empty);
        list.style.display = 'block';
        return;
      }
      items.forEach(function(it) {
        var row = document.createElement('div');
        row.className = 'ub-ac-item';
        var top = document.createElement('div');
        var spanRfc = document.createElement('span');
        spanRfc.className = 'ub-ac-rfc';
        spanRfc.textContent = it.rfc;
        var spanNom = document.createElement('span');
        spanNom.className = 'ub-ac-name';
        spanNom.textContent = it.nombre;
        top.appendChild(spanRfc);
        top.appendChild(spanNom);
        row.appendChild(top);
        if (it.id_ubicacion) {
          var sub = document.createElement('div');
          sub.className = 'ub-ac-sub';
          sub.textContent = it.id_ubicacion + (it.estado ? ' · ' + it.estado : '');
          row.appendChild(sub);
        }
        row.addEventListener('mousedown', function(e) {
          e.preventDefault(); /* no pierde foco el input */
          _skip = true;
          applySelection(it);
          list.style.display = 'none';
        });
        list.appendChild(row);
      });
      list.style.display = 'block';
    }

    function applySelection(it) {
      /* campos principales */
      rfcEl.value = it.rfc || '';
      var nomEl = document.getElementById('Nombre' + s);
      if (nomEl) nomEl.value = it.nombre || '';
      var idEl = document.getElementById('IDUbicacion' + s);
      if (idEl) idEl.value = it.id_ubicacion ? it.id_ubicacion.replace(/^(OR|DE)/i, '') : '';

      /* dirección: si hay datos, abrir automáticamente y rellenar */
      if (it.calle || it.codigo_postal || it.estado) {
        var chkDir = document.getElementById('agregar_dir_' + tipo + '30');
        var divDir = document.querySelector('.ub-dir-' + tipo);
        if (chkDir && !chkDir.checked) {
          chkDir.checked = true;
          chkDir.value = '1';
          if (divDir) divDir.style.display = 'flex';
        }
        var f = function(id, v) { var el = document.getElementById(id); if (el) el.value = v || ''; };
        f('dir_cp'        + s, it.codigo_postal);
        f('dir_calle'     + s, it.calle);
        f('dir_numext'    + s, it.numero_exterior);
        f('dir_numint'    + s, it.numero_interior);
        f('dir_colonia'   + s, it.colonia);
        f('dir_municipio' + s, it.municipio);
        f('dir_estado'    + s, it.estado);
      }
    }

    rfcEl.addEventListener('input', function() {
      if (_skip) { _skip = false; return; }
      clearTimeout(_timer);
      var q = rfcEl.value.trim();
      if (q.length < 2) { list.style.display = 'none'; return; }
      _timer = setTimeout(function() { fetchSuggestions(q); }, 280);
    });

    rfcEl.addEventListener('blur', function() {
      setTimeout(function() { list.style.display = 'none'; }, 200);
    });

    rfcEl.addEventListener('focus', function() {
      var q = rfcEl.value.trim();
      if (q.length >= 2) fetchSuggestions(q);
    });
  }

