                    extra: '1-002-Tasa-0.160000-IVA_16%'
                }]
            };
        });
    });
}

function recalcularImpuestosGlobales() {
    aTraslados = [];
    aRetenciones = [];
    localTraslados = [];
    localRetenciones = [];

    conceptos.forEach(function (c) {
        if (c.Impuestos && c.Impuestos.Traslados) {
            c.Impuestos.Traslados.forEach(function (imp) {
                var impKey, nombre;
                if (imp.extra) {
                    var tmp = String(imp.extra).split('-');
                    impKey = tmp[1] + '-' + tmp[2] + '-' + (tmp[3] || '');
                    nombre = tmp[4] || tmp[2] || impKey;
                } else {
                    impKey = imp.Impuesto + '-' + imp.TipoFactor + '-' + (imp.TasaOCuota || '');
                    nombre = impKey;
                }
                if (!aTraslados[impKey]) {
                    aTraslados[impKey] = { Importe: 0, Base: 0, Nombre: nombre };
                }
                aTraslados[impKey].Importe += parseFloat(imp.Importe || 0);
                aTraslados[impKey].Base += parseFloat(imp.Base || 0);
            });
        }
        if (c.Impuestos && c.Impuestos.Retenidos) {
            c.Impuestos.Retenidos.forEach(function (imp) {
                var impKey, nombre;
                if (imp.extra) {
                    var tmp = String(imp.extra).split('-');
                    impKey = tmp[1] + '-' + tmp[2] + '-' + (tmp[3] || '');
                    nombre = tmp[4] || impKey;
                } else {
                    impKey = imp.Impuesto + '-' + imp.TipoFactor + '-' + (imp.TasaOCuota || '');
                    nombre = impKey;
                }
                if (!aRetenciones[impKey]) {
                    aRetenciones[impKey] = { Importe: 0, Nombre: nombre };
                }
                aRetenciones[impKey].Importe += parseFloat(imp.Importe || 0);
            });
        }
        if (c.Locales && c.Locales.Traslados) {
            c.Locales.Traslados.forEach(function (imp) {
                var impKey = imp.ImpLocTrasladado + '-' + imp.TasadeTraslado;
                if (!localTraslados[impKey]) {
                    localTraslados[impKey] = {
                        Importe: 0,
                        Nombre: imp.ImpLocTrasladado + ' ' + imp.TasadeTraslado,
                        ImpLocTrasladado: imp.ImpLocTrasladado,
                        TasadeTraslado: imp.TasadeTraslado
                    };
                }
                localTraslados[impKey].Importe += parseFloat(imp.Importe || 0);
            });
        }
        if (c.Locales && c.Locales.Retenidos) {
            c.Locales.Retenidos.forEach(function (imp) {
                var impKey = imp.ImpLocRetenido + '-' + imp.TasadeRetencion;
                if (!localRetenciones[impKey]) {
                    localRetenciones[impKey] = {
                        Importe: 0,
                        Nombre: imp.ImpLocRetenido + ' ' + imp.TasadeRetencion,
                        ImpLocRetenido: imp.ImpLocRetenido,
                        TasadeRetencion: imp.TasadeRetencion
                    };
                }
                localRetenciones[impKey].Importe += parseFloat(imp.Importe || 0);
            });
        }
    });
}

function cfdiMarcarImpuestosConcepto(c) {
    $('.traslado, .retenido, .trasladoLoc, .retenidoLoc').prop('checked', false);

    function marcarLista(lista, selector) {
        if (!lista || !lista.length) return;
        lista.forEach(function (imp) {
            if (imp.extra) {
                $(selector).filter(function () { return $(this).val() === imp.extra; }).prop('checked', true);
                return;
            }
            if (imp.Impuesto) {
                $(selector).each(function () {
                    var tmp = $(this).val().split('-');
                    var matchImp = tmp[1] === imp.Impuesto && tmp[2] === imp.TipoFactor;
                    var matchTasa = imp.TipoFactor === 'Exento' || String(tmp[3]) === String(imp.TasaOCuota);
                    if (matchImp && matchTasa) {
                        $(this).prop('checked', true);
                    }
                });
                return;
            }
            if (imp.ImpLocTrasladado) {
                var valLocT = imp.ImpLocTrasladado + '-' + imp.TasadeTraslado;
                $(selector).filter(function () { return $(this).val() === valLocT; }).prop('checked', true);
            } else if (imp.ImpLocRetenido) {
                var valLocR = imp.ImpLocRetenido + '-' + imp.TasadeRetencion;
                $(selector).filter(function () { return $(this).val() === valLocR; }).prop('checked', true);
            }
        });
    }

    if (c.Impuestos) {
        marcarLista(c.Impuestos.Traslados, '.traslado');
        marcarLista(c.Impuestos.Retenidos, '.retenido');
    }
    if (c.Locales) {
        marcarLista(c.Locales.Traslados, '.trasladoLoc');
        marcarLista(c.Locales.Retenidos, '.retenidoLoc');
    }
}

