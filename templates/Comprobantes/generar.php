/* ═══════════════════════════════════════════════════════
   VALIDACIÓN CARTA PORTE 3.1 — Autotransporte
   Basada en CartaPorte31.xslt (SAT)
   Devuelve un array de {id, msg}; vacío = sin errores.
   ═══════════════════════════════════════════════════════ */
function validateCartaPorte() {
  var errs = [];

  var chk = document.getElementById('complementoCartaPorte30');
  if (!chk || !chk.checked) return errs;

  /* helper: campo requerido por id */
  function req(id, label) {
    var el = document.getElementById(id);
    if (!el || !el.value.trim()) errs.push({ id: id, msg: label });
  }

  /* helper: tabla debe tener al menos una fila */
  function needsRow(tbodySelector, label, focusId) {
    var rows = document.querySelectorAll(tbodySelector + ' tbody tr');
    if (!rows.length) errs.push({ id: focusId || null, msg: label });
  }

  /* ── 1. Raíz CartaPorte ── */
  req('IdCCP30',          'IdCCP es requerido');
  req('TranspInternac30', 'Transporte Internacional es requerido');

  /* Campos condicionales de Transporte Internacional */
  var transpInternac = document.getElementById('TranspInternac30');
  if (transpInternac && transpInternac.value.trim() === 'Sí') {
    req('EntradaSalidaMerc30', 'Entrada/Salida de Mercancía es requerida (transporte internacional)');
    req('PaisOrigenDestino30', 'País Origen/Destino es requerido (transporte internacional)');
    req('ViaEntradaSalida30',  'Vía Entrada/Salida es requerida (transporte internacional)');
  }

  /* Registro ISTMO */
  var regIstmo = document.getElementById('RegistroISTMO30');
  if (regIstmo && regIstmo.value.trim() === 'Sí') {
    req('UbicacionPoloOrigen30',  'Ubicación Polo Origen es requerida (Registro ISTMO)');
    req('UbicacionPoloDestino30', 'Ubicación Polo Destino es requerida (Registro ISTMO)');
  }

  /* ── 2. Ubicaciones: al menos 1 Origen y 1 Destino ── */
  needsRow('#ubicaciones_origen30', 'Se requiere al menos una Ubicación de tipo Origen', null);
  needsRow('#ubicaciones_destino30', 'Se requiere al menos una Ubicación de tipo Destino', null);

  /* ── 3. Mercancías ── */
  req('PesoBrutoTotal30', 'Peso Bruto Total (Mercancías) es requerido');
  req('UnidadPeso30',     'Unidad de Peso (Mercancías) es requerida');
  needsRow('#tbmercancias30', 'Debe agregar al menos una Mercancía', 'BienesTransp30');

  /* ── 4. Autotransporte ── */
  var chkAuto = document.getElementById('cp_autotransporte_30');
  if (!chkAuto || !chkAuto.checked) {
    errs.push({ id: 'cp_autotransporte_30', msg: 'Debe activar y completar la sección Autotransporte' });
  } else {
    /* Permiso SCT */
    req('PermSCT30',          'Permiso SCT (Autotransporte) es requerido');
    req('NumeroPermisoSCT30', 'Número de Permiso SCT es requerido');

    /* Identificación Vehicular */
    req('ConfigVehicular30',    'Configuración Vehicular es requerida');
    req('PesoBrutoVehicular30', 'Peso Bruto Vehicular es requerido');
    req('PlacaVM30',            'Placa del Vehículo Motriz es requerida');
    req('AnioModeloVM30',       'Año Modelo del Vehículo es requerido');

    /* Seguros */
    req('AseguraRespCivil30', 'Aseguradora de Responsabilidad Civil es requerida');
    req('PolizaRespCivil30',  'Póliza de Responsabilidad Civil es requerida');
    /* Seguro Med. Ambiente: solo si hay material peligroso */
    var matPeli = document.getElementById('matpeligrososeguros');
    if (matPeli && parseInt(matPeli.value, 10) > 0) {
      req('AseguraMedAmbiente30', 'Aseguradora Medio Ambiente es requerida (mercancía peligrosa)');
      req('PolizaMedAmbiente30',  'Póliza Medio Ambiente es requerida (mercancía peligrosa)');
    }

    /* Remolques (condicional: solo si el checkbox está activo) */
    var chkRem = document.getElementById('Remolque30');
    if (chkRem && chkRem.checked) {
      req('SubTipoRem30', 'Sub Tipo de Remolque 1 es requerido');
      req('Placa30',      'Placa del Remolque 1 es requerida');
    }
  }

  /* ── 5. Figura Transporte ── */
  var chkFig = document.getElementById('FiguraTransporte30');
  if (!chkFig || !chkFig.checked) {
    errs.push({ id: 'FiguraTransporte30', msg: 'Debe activar y registrar al menos una Figura de Transporte' });
  } else {
    needsRow('#tbfiguratransporte30', 'Se requiere al menos una Figura de Transporte registrada', 'TipoFigura30');

    // Reglas SAT (Figura Transporte) basadas en el JSON capturado
    // Nota: la validación contra l_RFC (SAT) no es posible sin un servicio/lista local.
    var figInput = document.getElementById('inFiguraTransporta30');
    var figuras = [];
    if (figInput && figInput.value && figInput.value.trim()) {
      try { figuras = JSON.parse(figInput.value); } catch (e) { figuras = []; }
    }

    function tipoCode(tipoFigura) {
      var s = String(tipoFigura || '').trim();
      if (!s) return '';
      // "01-Operador" -> "01"
      return s.split('-')[0];
    }

    function isBlank(v) {
      return v === undefined || v === null || String(v).trim() === '';
    }

    function rfcBasicoValido(rfc) {
      var s = String(rfc || '').trim().toUpperCase();
      if (!s) return false;
      // RFC genérico extranjero permitido en Carta Porte
      if (s === 'XEXX010101000') return true;
      // RFC persona moral (12) o física (13)
      return /^[A-ZÑ&]{3,4}\d{6}[A-Z0-9]{3}$/.test(s);
    }

    // Cuando exista Mercancias:Autotransporte (en esta UI lo controlamos con cp_autotransporte_30),
    // debe existir al menos una figura con TipoFigura=01 (Operador).
    if (chkAuto && chkAuto.checked) {
      var hasOperador = false;
      for (var i = 0; i < figuras.length; i++) {
        if (tipoCode(figuras[i] && figuras[i].TipoFigura) === '01') { hasOperador = true; break; }
      }
      if (!hasOperador) {
        errs.push({ id: 'TipoFigura30', msg: 'Debe registrar al menos una Figura de Transporte con Tipo Figura 01 (Operador) cuando use Autotransporte' });
      }
    }

    // Validaciones por figura
    for (var j = 0; j < figuras.length; j++) {
      var f = figuras[j] || {};
      var t = tipoCode(f.TipoFigura);

      // NumLicencia requerido si TipoFigura=01
      if (t === '01' && isBlank(f.NumLicencia)) {
        errs.push({ id: 'NumLicencia30', msg: 'Número de Licencia es requerido para Tipo Figura 01 (Operador)' });
        break;
      }

      // PartesTransporte requerido si TipoFigura=02 o 03
      if ((t === '02' || t === '03')) {
        var partes = f.PartesTransporte;
        var okPartes = Array.isArray(partes) ? partes.length > 0 : !isBlank(partes);
        if (!okPartes) {
          errs.push({ id: 'carta_porte_figura_transporte_ParteTransporte30', msg: 'Partes Transporte es requerido cuando Tipo Figura es 02 o 03' });
          break;
        }
      }

      // RFCFigura vs NumRegIdTribFigura
      var rfcFig = String(f.RFCfigura || '').trim();
      var numReg = String(f.NumRegIdTribFigura || '').trim();
      var residencia = String(f.ResidenciaFiscalFigura || '').trim();

      if (!isBlank(rfcFig)) {
        // No podemos validar contra l_RFC; al menos validamos formato.
        if (!rfcBasicoValido(rfcFig)) {
          errs.push({ id: 'RFCfigura30', msg: 'RFC de la Figura no tiene un formato válido (o use NumRegIdTribFigura para extranjeros)' });
          break;
        }
        // Si RFC es extranjero genérico, debe traer NumRegIdTribFigura
        if (rfcFig.toUpperCase() === 'XEXX010101000' && isBlank(numReg)) {
          errs.push({ id: 'NumRegIdTribFigura30', msg: 'NumRegIdTribFigura es requerido cuando RFCFigura es XEXX010101000' });
          break;
        }
      } else {
        // Cuando RFCFigura no contenga un valor, NumRegIdTribFigura debe existir
        if (isBlank(numReg)) {
          errs.push({ id: 'NumRegIdTribFigura30', msg: 'NumRegIdTribFigura es requerido cuando no se registra RFCFigura' });
          break;
        }
      }

      // ResidenciaFiscalFigura requerido cuando exista NumRegIdTribFigura (y distinta a MEX)
      if (!isBlank(numReg)) {
        if (isBlank(residencia)) {
          errs.push({ id: 'ResidenciaFiscalFigura30', msg: 'ResidenciaFiscalFigura es requerida cuando existe NumRegIdTribFigura' });
          break;
        }
        if (residencia.toUpperCase() === 'MEX') {
          errs.push({ id: 'ResidenciaFiscalFigura30', msg: 'ResidenciaFiscalFigura debe ser distinta a MEX cuando existe NumRegIdTribFigura' });
          break;
        }
      }

      // Domicilio: si se capturó dirección, exigir mínimos.
      // (Reglas finas de catálogos c_Colonia/c_Localidad/c_Municipio/c_CodigoPostal requieren catálogos locales o servicio.)
      if (String(f.direccion || '').trim() === '1') {
        var pais = String(f.figuraPais || '').trim();
        var estado = String(f.figuraEstado || '').trim();
